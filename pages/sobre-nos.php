                <h2 id="studio-history">Como nasceu a VORTEX</h2>
                <p>A VORTEX nasceu em 2026, a partir da vontade de Rafael Azevedo, um desenvolvedor apaixonado por jogos, de transformar uma ideia simples em uma experiência que desse vontade de repetir. O ponto de partida não foi um grande estúdio: foi um projeto de sala de aula e a curiosidade de descobrir até onde ele poderia chegar.</p>
                <p>Entre linhas de código, desenhos de interface e muitas tentativas, o projeto começou a ganhar identidade. A proposta era reunir o que torna os arcades tão envolventes: aprender rápido, reconhecer os próprios erros e querer melhorar na próxima partida.</p>
                <p>O nome VORTEX veio da imagem de um redemoinho, sempre em movimento. Ele representa o processo de criar, testar e recomeçar. Dessa ideia nasceu o estúdio fictício e seu primeiro jogo: <strong>Hero Jump</strong>.</p>
            </section>
            <section class="story-chapter" aria-labelledby="game-history">
                <span class="story-chapter-label">02 / O JOGO</span>
                <h2 id="game-history">A jornada do Hero Jump</h2>
                <p>Hero Jump começou como um exercício inspirado em um jogo de pulo desenvolvido durante as aulas. No início, o desafio era direto: saltar na hora certa e evitar os obstáculos. Aos poucos, aquela mecânica passou a receber novos cenários, personagens e uma apresentação própria.</p>
                <p>Pikachu, Bart, Sasuke e Sonic trouxeram diferentes universos para a mesma aventura. Cada personagem ganhou seu cenário, seu obstáculo e um item temático para coletar. As imagens foram organizadas, os coletáveis receberam animações e cada coleta passou a acrescentar pontos à partida.</p>
                <p>O jogo também ganhou velocidade progressiva, tela de abertura, instruções e um ranking com as dez maiores pontuações, salvo em banco de dados. A cada versão, os testes ajudaram a ajustar o funcionamento e a distinguir melhor o que representa um desafio do que representa uma recompensa.</p>
                <p>Hoje, Hero Jump mantém a simplicidade do primeiro salto e carrega tudo o que foi aprendido pelo caminho. Sua história continua sendo escrita a cada melhoria — e a cada nova tentativa de superar um recorde.</p>
